#!/usr/bin/env bash
set -Eeuo pipefail

REPO_DIR="$(cd "$(dirname "$0")" && pwd)"
DOTS_DIR="$REPO_DIR/dots"

FAILURES=0
DRY_RUN=false

run_cmd() {
  if $DRY_RUN; then
    local display=()
    for arg in "$@"; do
      [[ "$arg" == sudo_run ]] && arg=sudo
      display+=("$arg")
    done
    echo "[dry-run] ${display[*]}"
    return 0
  fi
  "$@"
}

die() {
  echo "[ERROR]: $*" >&2
  exit 1
}

warn() {
  echo "[WARN]: $*" >&2
  FAILURES=$((FAILURES + 1))
}

trap 'die "failed at line $LINENO"' ERR

# Keep sudo arguments in an array; never interpolate SUDO_PASS into a command
# string. The password is written directly to sudo's stdin instead.
sudo_run() {
  if $DRY_RUN; then
    echo "[dry-run] sudo $*"
    return 0
  fi
  if (( EUID == 0 )); then
    "$@"
  elif [[ -n "${SUDO_PASS:-}" ]]; then
    printf '%s\n' "$SUDO_PASS" | sudo -S "$@"
  else
    sudo "$@"
  fi
}

PLANNER="$REPO_DIR/bin/tui"

usage() {
  cat <<'EOF'
Usage: ./install.sh [OPTIONS]

Installs the Noon shell with the selected compositor. Package and component
selection is built by the shipped bin/tui binary and passed here as a plan;
this script is the executor and TUI is the default mode.

Options:
  --tui            Open the interactive checkbox installer
  --plan FILE      Execute a plan file generated by bin/tui
  -f, --force      Re-run repo setup even when it is already configured
  --all            Install every package set (NVIDIA variants excluded)
  --compositor ID  Use dots/$DISTRO/compositors/ID.conf (hyprland default)
  --apps           Install optional desktop applications
  --desktop        Install common GUI apps, media and audio tools
  --dev, --devel   Install build dependencies (selected by default)
  --misc, --extra  Install miscellaneous utilities and extras
  --gaming         Install gaming packages
  --nvidia         Auto-select a compatible driver for the detected GPU
  --nvidia-old     Install the 580xx NVIDIA legacy driver
  --nvidia-driver ID
                   Install a specific driver (open|latest|580xx|470xx|390xx|340xx;
                   available IDs depend on the distro)
  --no-libqt       Skip building and installing Noon-libqt
  --onlydots       Install shared dotfiles only (skip packages, libqt, wrapper)
  --components a,b Only install named shared components (home, wallpapers)
  --method copy|link
                   Install shared files by copying from the repo (default) or
                   symlinking them to the repo (directories stay real, files
                   become links)
  --remove         Remove Noon system files (QML modules and the noon wrapper)
  --dry-run        Print all actions without executing them
  -h, --help       Show this help

Flags other than --tui, --plan and --dry-run are forwarded to the planner. The
TUI saves its plan under $XDG_STATE_HOME/noon/install-plan.json (default
~/.local/state) so it can be inspected or replayed with --plan.
EOF
}

require_planner() {
  [[ -x "$PLANNER" ]] || die "missing $PLANNER (needed to build and read install plans)"
}

# --dry-run is executor-only; strip it before forwarding flags to the planner.
PLAN_ARGS=()
for arg in "$@"; do
  if [[ "$arg" == --dry-run ]]; then
    DRY_RUN=true
  else
    PLAN_ARGS+=("$arg")
  fi
done
set -- "${PLAN_ARGS[@]}"

# With no arguments and an interactive terminal, open the TUI by default.
if [[ $# -eq 0 && $DRY_RUN == false && -t 0 && -x "$PLANNER" ]]; then
  export NOON_REPO="$REPO_DIR"
  exec "$PLANNER"
fi

case "${1:-}" in
  --tui)
    $DRY_RUN && die "--dry-run cannot be combined with --tui"
    require_planner
    export NOON_REPO="$REPO_DIR"
    exec "$PLANNER"
    ;;
  -h|--help)
    usage
    exit 0
    ;;
  --plan)
    require_planner
    plan_file="${2:-}"
    [[ -n "$plan_file" && -f "$plan_file" ]] || die "--plan requires a plan file"
    plan_vars="$("$PLANNER" --plan-shell "$plan_file")" || die "could not read install plan"
    # shellcheck disable=SC2086
    eval "$plan_vars"
    if [[ "${NOON_PLAN_TEMP:-}" == 1 ]]; then
      trap 'rm -f "$plan_file"' EXIT
    fi
    ;;
  *)
    require_planner
    plan_file="$(mktemp "${TMPDIR:-/tmp}/noon-plan.XXXXXXXX.json")"
    export NOON_REPO="$REPO_DIR" NOON_PLAN_TEMP=1
    "$PLANNER" --plan --output "$plan_file" "$@" || die "failed to build install plan"
    dry_arg=()
    $DRY_RUN && dry_arg=(--dry-run)
    exec bash "$REPO_DIR/install.sh" --plan "$plan_file" "${dry_arg[@]}"
    ;;
esac

DISTRO="$PLAN_DISTRO"
case "$DISTRO" in
  fedora|arch) ;;
  *) die "unsupported distro in plan: $DISTRO" ;;
esac

declare -a SELECTED=("${PLAN_BUNDLES[@]}")
BUILD_LIBQT="$PLAN_LIBQT"
METHOD="$PLAN_METHOD"
ONLYDOTS="$PLAN_ONLYDOTS"
FORCE="$PLAN_FORCE"
REMOVE="$PLAN_REMOVE"
NVIDIA_DRIVER="$PLAN_NVIDIA"
case "$NVIDIA_DRIVER" in
  none) ;;
  *[!a-z0-9-]*) die "invalid plan NVIDIA selection: $NVIDIA_DRIVER" ;;
esac
COMPOSITOR="${PLAN_COMPOSITOR:-hyprland}"
if [[ "$COMPOSITOR" != none && "$COMPOSITOR" == *[!a-z0-9-]* ]]; then
  die "invalid plan compositor selection: $COMPOSITOR"
fi
# Only the chosen compositor's config directory is installed with the home dots.
OTHER_COMPOSITOR_DIRS=()
if [[ "$COMPOSITOR" != none ]]; then
  for conf in "$DOTS_DIR/$DISTRO"/compositors/*.conf; do
    [[ -f "$conf" ]] || continue
    id="${conf##*/}"
    id="${id%.conf}"
    [[ "$id" == "$COMPOSITOR" ]] && continue
    dir="$id"
    [[ "$id" == hyprland ]] && dir=hypr
    OTHER_COMPOSITOR_DIRS+=("$dir")
  done
fi
COMPONENTS="$(IFS=,; echo "${PLAN_COMPONENTS[*]}")"

AUR_HELPER=""
if [[ "$DISTRO" == arch ]]; then
  if command -v yay &>/dev/null; then
    AUR_HELPER="yay"
  elif command -v paru &>/dev/null; then
    AUR_HELPER="paru"
  fi
fi

pkg_install() {
  if [[ "$DISTRO" == fedora ]]; then
    sudo_run dnf install --skip-file-locks -y "$@"
  elif [[ -n "$AUR_HELPER" ]]; then
    run_cmd "$AUR_HELPER" -S --needed --noconfirm "$@"
  else
    sudo_run pacman -S --needed --noconfirm "$@"
  fi
}

qml_install_dir() {
  local dir=""
  if command -v qtpaths6 &>/dev/null; then
    dir="$(qtpaths6 --query QT_INSTALL_QML 2>/dev/null || true)"
  elif command -v qtpaths &>/dev/null; then
    dir="$(qtpaths --query QT_INSTALL_QML 2>/dev/null || true)"
  fi
  if [[ -z "$dir" ]]; then
    for candidate in /usr/lib64/qt6/qml /usr/lib/qt6/qml; do
      [[ -d "$candidate" ]] && dir="$candidate" && break
    done
  fi
  echo "$dir"
}

remove_stale_qml() {
  local qml_dir
  qml_dir="$(qml_install_dir)"
  [[ -z "$qml_dir" || ! -d "$qml_dir/Noon" ]] && return 0
  # Modules that were removed from Noon-libqt or are not imported by the shell.
  for module in Network Devices Blobs Scrcpy QR; do
    if [[ -e "$qml_dir/Noon/$module" ]]; then
      echo "  Removing stale QML module $module"
      sudo_run rm -rf "$qml_dir/Noon/$module"
    fi
  done
}

install_libqt() {
  local libqt_dir=""

  for candidate in "${NOON_LIBQT_DIR:-}" "$REPO_DIR/Noon-libqt" "$REPO_DIR/../Noon-libqt" "$HOME/.local/src/noon-libqt"; do
    if [[ -n "$candidate" && -f "$candidate/CMakeLists.txt" ]]; then
      libqt_dir="$candidate"
      break
    fi
  done

  if [[ -z "$libqt_dir" ]]; then
    local clone_dir="$HOME/.local/src/noon-libqt"
    echo "[libqt] Noon-libqt not found, cloning into $clone_dir"
    run_cmd mkdir -p "$(dirname "$clone_dir")"
    if ! run_cmd git clone --depth 1 https://github.com/pharmaragist/Noon-libqt.git "$clone_dir"; then
      warn "could not clone Noon-libqt; C++ QML modules will be missing"
      return 0
    fi
    libqt_dir="$clone_dir"
  fi

  if ! command -v cmake &>/dev/null; then
    warn "cmake not found; skipping Noon-libqt build"
    return 0
  fi

  local generator=()
  command -v ninja &>/dev/null && generator=(-G Ninja)
  local build_dir="$libqt_dir/build-noon"

  local nvidia_flag=(-DNVIDIA=OFF)
  if [[ "$NVIDIA_DRIVER" != none ]]; then
    if command -v pkg-config &>/dev/null && pkg-config --exists nvidia-ml; then
      echo "[libqt] NVIDIA driver selected; enabling NVML GPU stats"
      nvidia_flag=(-DNVIDIA=ON)
    else
      warn "NVIDIA driver selected but nvidia-ml.pc not found; building without GPU stats"
    fi
  fi

  echo "[libqt] Configuring $libqt_dir"
  run_cmd cmake -S "$libqt_dir" -B "$build_dir" "${generator[@]}" \
    -DCMAKE_BUILD_TYPE=Release \
    -DSCRCPY=OFF \
    "${nvidia_flag[@]}"

  echo "[libqt] Building"
  run_cmd cmake --build "$build_dir" -j"$(nproc)"

  echo "[libqt] Installing"
  sudo_run cmake --install "$build_dir"

  remove_stale_qml
}

# ---- Fedora-specific repos ----
if ! $ONLYDOTS && [[ "$DISTRO" == fedora ]]; then
  if $FORCE || ! rpm -q rpmfusion-free-release rpmfusion-nonfree-release &>/dev/null; then
    sudo_run dnf install --nogpgcheck --skip-file-locks \
      https://download1.rpmfusion.org/free/fedora/rpmfusion-free-release-"$(rpm -E %fedora)".noarch.rpm \
      https://download1.rpmfusion.org/nonfree/fedora/rpmfusion-nonfree-release-"$(rpm -E %fedora)".noarch.rpm -y
  fi

  if $FORCE || ! rpm -q terra-release &>/dev/null; then
    # Capture first: grep -q can close the pipe early and trip pipefail.
    dnf_repos="$(dnf repolist 2>/dev/null || true)"
    if grep -q "^terra" <<<"$dnf_repos"; then
      echo "[WARN]: terra repo already configured, skipping"
    else
      # dnf expands $releasever itself; keep the literal string.
      # shellcheck disable=SC2016
      sudo_run dnf install --nogpgcheck --skip-file-locks \
        --repofrompath 'terra,https://repos.fyralabs.com/terra$releasever' \
        terra-release -y || warn "terra repo setup failed"
    fi
  fi
fi

flush_block() {
  local type="$1"; shift
  local items=("$@")
  [[ ${#items[@]} -eq 0 ]] && return
  case "$type" in
    copr)
      if [[ "$DISTRO" != fedora ]]; then
        echo "[WARN]: COPR not supported on $DISTRO, skipping"
        return
      fi
      # Capture first: grep -q can close the pipe early and trip pipefail.
      local copr_listing
      copr_listing="$(dnf copr list 2>/dev/null || true)"
      for repo in "${items[@]}"; do
        if $FORCE || ! grep -q "$repo" <<<"$copr_listing"; then
          sudo_run dnf copr enable "$repo" -y || warn "failed to enable COPR $repo"
        fi
      done
      ;;
    pkgs)
      pkg_install "${items[@]}" || warn "some packages failed to install"
      ;;
    python)
      run_cmd uv pip install --system "${items[@]}" || warn "some python packages failed to install"
      ;;
    script)
      for s in "${items[@]}"; do
        run_cmd bash "$DOTS_DIR/$DISTRO/$s" || warn "script $s failed"
      done
      ;;
  esac
}

process_config() {
  local conf="$1"
  [[ ! -f "$conf" ]] && return
  local -a copr_list=() pkgs_list=() python_list=() script_list=()
  local block_type="" block_items=()
  while IFS= read -r line; do
    line="${line#"${line%%[! ]*}"}"
    [[ -z "$line" || "$line" =~ ^# ]] && continue
    if [[ -n "$block_type" ]]; then
      if [[ "$line" == "}" ]]; then
        case "$block_type" in
          copr)   copr_list+=("${block_items[@]}") ;;
          pkgs)   pkgs_list+=("${block_items[@]}") ;;
          python) python_list+=("${block_items[@]}") ;;
          script) script_list+=("${block_items[@]}") ;;
        esac
        block_type=
        block_items=()
      else
        for item in $line; do
          [[ -n "$item" ]] && block_items+=("$item")
        done
      fi
    else
      if [[ "$line" =~ ^(copr|pkgs|python|script)[[:space:]]*\{[[:space:]]*$ ]]; then
        block_type="${BASH_REMATCH[1]}"
        block_items=()
      fi
    fi
  done < "$conf"
  if [[ -n "$block_type" && ${#block_items[@]} -gt 0 ]]; then
    case "$block_type" in
      copr)   copr_list+=("${block_items[@]}") ;;
      pkgs)   pkgs_list+=("${block_items[@]}") ;;
      python) python_list+=("${block_items[@]}") ;;
      script) script_list+=("${block_items[@]}") ;;
    esac
  fi
  # Flush in dependency order: copr -> pkgs -> script -> python
  flush_block copr   "${copr_list[@]}"
  flush_block pkgs   "${pkgs_list[@]}"
  flush_block script "${script_list[@]}"
  flush_block python "${python_list[@]}"
}

if $REMOVE; then
  echo "Removing Noon system files..."
  qml_dir="$(qml_install_dir)"
  if [[ -n "$qml_dir" && -d "$qml_dir/Noon" ]]; then
    sudo_run rm -rf "$qml_dir/Noon"
  fi
  sudo_run rm -f /usr/local/bin/noon
  echo "Removed system files. User dotfiles were left untouched."
  exit 0
fi

for name in "${SELECTED[@]}"; do
  conf="$DOTS_DIR/$DISTRO/$name.conf"
  if [[ -f "$conf" ]]; then
    echo "==> Installing $name packages"
    process_config "$conf"
  elif [[ "$name" == "core" ]]; then
    warn "missing $conf; install the shell dependencies manually"
  fi
done

if [[ "$COMPOSITOR" != none ]]; then
  compositor_conf="$DOTS_DIR/$DISTRO/compositors/$COMPOSITOR.conf"
  [[ -f "$compositor_conf" ]] || die "missing compositor config: $compositor_conf"
  echo "==> Installing $COMPOSITOR compositor"
  process_config "$compositor_conf"
fi

if [[ "$NVIDIA_DRIVER" != none ]]; then
  nvidia_conf="$DOTS_DIR/$DISTRO/nvidia/$NVIDIA_DRIVER.conf"
  [[ -f "$nvidia_conf" ]] || die "missing NVIDIA driver config: $nvidia_conf"
  echo "==> Installing $NVIDIA_DRIVER NVIDIA driver"
  process_config "$nvidia_conf"
fi

if $BUILD_LIBQT; then
  install_libqt
fi

# Process shared directories with INSTALLER_CONFIG
SHARED_DIR="$DOTS_DIR/shared"
shopt -s dotglob nullglob
if [[ -d "$SHARED_DIR" ]]; then
  for component in "$SHARED_DIR"/*/; do
    [[ -d "$component" ]] || continue
    component="${component%/}"
    config="$component/INSTALLER_CONFIG"
    [[ -f "$config" ]] || continue

    cname="$(basename "$component")"
    wanted=()
    IFS=',' read -ra wanted <<<"$COMPONENTS"
    match=false
    for w in "${wanted[@]}"; do
      [[ "$w" == "$cname" ]] && match=true && break
    done
    $match || continue

    dest_path="" type_name=""
    while IFS='=' read -r key value; do
      key="${key#"${key%%[! ]*}"}"
      value="${value#"${value%%[! ]*}"}"
      [[ -z "$key" || "$key" =~ ^# ]] && continue
      case "$key" in
        DESTINATION) dest_path="$value" ;;
        TYPE)        type_name="$value" ;;
      esac
    done < "$config"
    if [[ -n "$dest_path" && -n "$type_name" ]]; then
      dest_path="${dest_path/#\$HOME/$HOME}"
      echo "[$type_name] Installing ($METHOD)..."
      # HOME destinations are written as the user; system destinations go through sudo.
      dest_cmd=()
      [[ "$dest_path" == "$HOME"* ]] || dest_cmd=(sudo_run)
      # -a preserves metadata. -s turns files into links back into the repo;
      # directories stay real so files the user adds there are not hidden.
      # --remove-destination keeps switch back from link from writing into the repo.
      cp_flags=(-a --remove-destination)
      [[ "$METHOD" == link ]] && cp_flags=(-afs)
      run_cmd "${dest_cmd[@]}" mkdir -p "$dest_path"
      for item in "$component"/*; do
        name="$(basename "$item")"
        [[ "$name" == "INSTALLER_CONFIG" ]] && continue
        if [[ "$name" == ".config" && ${#OTHER_COMPOSITOR_DIRS[@]} -gt 0 ]]; then
          run_cmd "${dest_cmd[@]}" mkdir -p "$dest_path/.config"
          for entry in "$item"/*; do
            skip=false
            for dir in "${OTHER_COMPOSITOR_DIRS[@]}"; do
              [[ "$(basename "$entry")" == "$dir" ]] && skip=true && break
            done
            $skip && continue
            run_cmd "${dest_cmd[@]}" cp "${cp_flags[@]}" "$entry" "$dest_path/.config/" || warn "failed to install $(basename "$entry")"
          done
          continue
        fi
        run_cmd "${dest_cmd[@]}" cp "${cp_flags[@]}" "$item" "$dest_path/" || warn "failed to install $name"
      done
      if [[ "$type_name" == "fonts" ]]; then
        sudo_run fc-cache -f 2>/dev/null || true
      fi
    fi
  done
fi
shopt -u dotglob nullglob

# The session starts the shell through /usr/local/bin/noon.
if ! $ONLYDOTS; then
  sudo_run bash "$DOTS_DIR/install-binary.sh"
fi

if (( FAILURES > 0 )); then
  die "$FAILURES operation(s) failed; see the [WARN] lines above"
fi

if $ONLYDOTS; then
  echo "Dotfiles installed"
else
  echo "All packages installed"
fi
