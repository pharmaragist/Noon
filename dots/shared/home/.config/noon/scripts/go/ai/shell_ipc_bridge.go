type tool struct {
	target string
	fn     string
	params []string
	desc   string
}

func (t tool) ipcName() string { return t.target + "_" + t.fn }

var fallback = []tool{
	{target: "global", fn: "toast", params: []string{"info", "state"}},
	{target: "noon", fn: "translate", params: []string{"query"}},
	{target: "global", fn: "say", params: []string{"text"}},
}

var (
	targetRe = regexp.MustCompile(`^target (\S+)\s*$`)
	fnRe     = regexp.MustCompile(`^\s*function (\w+)\(([^)]*)\)`)
	descRe   = regexp.MustCompile(`^\s*//\*\s*(.+?)\s*$`)
)

func parseTools(out string) []tool {
	var tools []tool
	seen := map[string]bool{}
	target := ""
	for _, line := range strings.Split(out, "\n") {
		if m := targetRe.FindStringSubmatch(line); m != nil {
			target = m[1]
			continue
		}
		if target == "" {
			continue
		}
		if m := fnRe.FindStringSubmatch(line); m != nil {
			name := m[1]
			var params []string
			for _, p := range strings.Split(m[2], ",") {
				p = strings.TrimSpace(p)
				if i := strings.Index(p, ":"); i >= 0 {
					p = strings.TrimSpace(p[:i])
				}
				if p != "" {
					params = append(params, p)
				}
			}
			key := target + "_" + name
			if !seen[key] {
				seen[key] = true
				tools = append(tools, tool{target: target, fn: name, params: params})
			}
		}
	}
	return tools
}

func enrichDescriptions(shellRoot string, tools []tool) {
	descs := map[string]string{}
	files := []string{
		filepath.Join(shellRoot, "GlobalIPC.qml"),
		filepath.Join(shellRoot, "modules", "main", "NIPC.qml"),
	}
	for _, path := range files {
		data, err := os.ReadFile(path)
		if err != nil {
			continue
		}
		pending := ""
		for _, line := range strings.Split(string(data), "\n") {
			if m := descRe.FindStringSubmatch(line); m != nil {
				pending = strings.TrimSpace(m[1])
				continue
			}
			if m := fnRe.FindStringSubmatch(line); m != nil {
				if pending != "" {
					if _, ok := descs[m[1]]; !ok {
						descs[m[1]] = pending
					}
					pending = ""
				}
				continue
			}
			if strings.TrimSpace(line) != "" && !strings.HasPrefix(strings.TrimSpace(line), "//") {
				pending = ""
			}
		}
	}
	for i, t := range tools {
		if d, ok := descs[t.fn]; ok {
			tools[i].desc = d
		} else {
			tools[i].desc = "Noon shell: " + t.target + " " + t.fn
		}
	}
}

func cmdGenTools(shellRoot string) error {
	ctx, cancel := context.WithTimeout(context.Background(), 15*time.Second)
	defer cancel()
	out, err := exec.CommandContext(ctx, "qs", "-p", shellRoot, "ipc", "show").Output()
	tools := fallback
	if err == nil {
		if parsed := parseTools(string(out)); len(parsed) > 0 {
			tools = parsed
		}
	}
	enrichDescriptions(shellRoot, tools)
	var sb strings.Builder
	sb.WriteString("// Generated by Noon shell (harness gen-tools). Do not edit by hand.\n")
	sb.WriteString("import { tool } from \"@opencode-ai/plugin\";\n\n")
	sb.WriteString("const SHELL_ROOT = " + strconv.Quote(shellRoot) + ";\n\n")
	sb.WriteString(`async function shellIpc(target: string, fn: string, params: string[], values: Record<string, unknown>): Promise<string> {
  const argv: string[] = ["qs", "-p", SHELL_ROOT, "ipc", "call", target, fn];
  for (const p of params) {
    const v = values[p];
    argv.push(v === undefined || v === null ? "" : String(v));
  }
  const proc = Bun.spawn(argv, { stdout: "pipe", stderr: "pipe" });
  const [out, err, code] = await Promise.all([
    new Response(proc.stdout).text(),
    new Response(proc.stderr).text(),
    proc.exited,
  ]);
  const text = (out + err).trim();
  if (code !== 0)
    throw new Error(text === "" ? fn + " exited " + code : text);
  return text;
}

`)
	for _, t := range tools {
		name := t.target + "_" + t.fn
		sb.WriteString("export const " + name + " = tool({\n")
		sb.WriteString("  description: " + strconv.Quote(t.desc) + ",\n")
		sb.WriteString("  args: {\n")
		for _, p := range t.params {
			sb.WriteString("    " + p + ": tool.schema.string().describe(" + strconv.Quote(p) + "),\n")
		}
		sb.WriteString("  },\n")
		sb.WriteString("  async execute(args) {\n")
		sb.WriteString("    return await shellIpc(" + strconv.Quote(t.target) + ", " + strconv.Quote(t.fn) + ", [")
		for i, p := range t.params {
			if i > 0 {
				sb.WriteString(", ")
			}
			sb.WriteString(strconv.Quote(p))
		}
		sb.WriteString("], args);\n  },\n});\n\n")
	}
	fmt.Print(sb.String())
	return nil
}

func cleanJSONC(src string) string {
	var sb strings.Builder
	inStr, esc := false, false
	i, n := 0, len(src)
	isWS := func(c byte) bool { return c == ' ' || c == '\t' || c == '\n' || c == '\r' }
	for i < n {
		c := src[i]
		if inStr {
			sb.WriteByte(c)
			if esc {
				esc = false
			} else if c == '\\' {
				esc = true
			} else if c == '"' {
				inStr = false
			}
			i++
			continue
		}
		switch {
		case c == '"':
			inStr = true
			sb.WriteByte(c)
			i++
		case c == '/' && i+1 < n && src[i+1] == '/':
			for i < n && src[i] != '\n' {
				i++
			}
		case c == '/' && i+1 < n && src[i+1] == '*':
			i += 2
			for i+1 < n && !(src[i] == '*' && src[i+1] == '/') {
				i++
			}
			i += 2
			if i > n {
				i = n
			}
		case c == ',':
			j := i + 1
			for j < n && isWS(src[j]) {
				j++
			}
			if j < n && (src[j] == '}' || src[j] == ']') {
				i++
				continue
			}
			sb.WriteByte(c)
			i++
		default:
			sb.WriteByte(c)
			i++
		}
	}
	return sb.String()
}

func permFill(m map[string]interface{}) {
	p, _ := m["permission"].(map[string]interface{})
	if p == nil {
		p = map[string]interface{}{}
		m["permission"] = p
	}
	if _, ok := p["*"]; !ok {
		p["*"] = "ask"
	}
	if _, ok := p["read"]; !ok {
		p["read"] = "allow"
	}
}

func writeJSON(path string, v interface{}) error {
	b, err := json.MarshalIndent(v, "", "  ")
	if err != nil {
		return err
	}
	return os.WriteFile(path, append(b, '\n'), 0644)
}

func cmdSyncConfig(globalCfg, sideDir string) error {
	if globalCfg == "" || sideDir == "" {
		return fmt.Errorf("sync-config needs <globalCfg> <sideDir>")
	}
	raw, err := os.ReadFile(globalCfg)
	if err != nil {
		raw = []byte("{}")
	}
	var global map[string]interface{}
	if err := json.Unmarshal([]byte(cleanJSONC(string(raw))), &global); err != nil {
		return fmt.Errorf("parse %s: %w", globalCfg, err)
	}
	if global == nil {
		global = map[string]interface{}{}
	}
	if ins, ok := global["instructions"].([]interface{}); ok {
		kept := []interface{}{}
		for _, e := range ins {
			if s, ok := e.(string); ok && strings.Contains(s, "harness/main.md") {
				continue
			}
			kept = append(kept, e)
		}
		global["instructions"] = kept
	}
	if d, ok := global["default_agent"].(string); ok && d == "noon" {
		delete(global, "default_agent")
	}
	permFill(global)
	if err := writeJSON(globalCfg, global); err != nil {
		return err
	}
	scopedJSON, err := json.Marshal(global)
	if err != nil {
		return err
	}
	var scoped map[string]interface{}
	if err := json.Unmarshal(scopedJSON, &scoped); err != nil {
		return err
	}
	scoped["default_agent"] = "noon"
	permFill(scoped)
	if err := os.MkdirAll(filepath.Join(sideDir, "agents"), 0755); err != nil {
		return err
	}
	if err := os.MkdirAll(filepath.Join(sideDir, "tools"), 0755); err != nil {
		return err
	}
	ents, err := os.ReadDir(filepath.Dir(globalCfg))
	if err != nil {
		return err
	}
	skip := map[string]bool{"opencode.jsonc": true, "opencode.jsonc.tmp": true, "agents": true, "tools": true, "system.md": true}
	for _, e := range ents {
		if skip[e.Name()] {
			continue
		}
		dst := filepath.Join(sideDir, e.Name())
		if _, err := os.Lstat(dst); err == nil {
			continue
		}
		os.Symlink(filepath.Join(filepath.Dir(globalCfg), e.Name()), dst)
	}
	os.Remove(filepath.Join(sideDir, "opencode.jsonc.tmp"))
	if err := writeJSON(filepath.Join(sideDir, "opencode.jsonc"), scoped); err != nil {
		return err
	}
	fmt.Print("ok")
	return nil
}
